const photo = (name: string, alt: string) => ({ src: `/demo/${name}.webp`, alt });

function departure(
  id: string,
  startsOn: string,
  days: number,
  priceUsd: number,
  seatsTotal: number,
  seatsBooked: number,
  status: Departure["status"] = "open",
): Departure {
  const end = new Date(`${startsOn}T00:00:00Z`);
  end.setUTCDate(end.getUTCDate() + days - 1);
  return {
    id,
    startsOn,
    endsOn: end.toISOString().slice(0, 10),
    priceCents: priceUsd * 100,
    seatsTotal,
    seatsBooked,
    status: seatsBooked >= seatsTotal ? "full" : status,
  };
}

const privatePrices = (...rows: [number, number, number][]) =>
  rows.map(([groupSizeFrom, groupSizeTo, usd]) => ({
    groupSizeFrom,
    groupSizeTo,
    pricePerPersonCents: usd * 100,
  }));

